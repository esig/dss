package eu.europa.esig.dss.enumerations;

/**
 * List of supported attestation forms
 *
 */
public enum AttestationForm {

    /**
     * Represents an IETF RFC 9901 "Selective Disclosure for JSON Web Tokens" token.
     */
    SD_JWT,

    /**
     * Represents an mdoc structure as per ISO/IEC 18013-5
     */
    MDOC

}
